#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Loot table export (contract section 15).

- scans src/main/resources/assets/hbm/loot_tables/**/*.json and summarises them into docs/loot-tables.md:
  per table it lists the name / purpose / pool names / entries so a pack author can reference them from zs.
- also checks the two hard requirements of section 15: a table outside the minecraft namespace must give every pool a unique name;
  and any entry meant to be removed on its own should carry an entryName. Under --strict a violation exits 1, so it can go into acceptance.
- when no tables exist yet (empty directory) it still writes the report, saying they land with the content layer.

No third-party dependencies, python3 stdlib only.

Usage:
  python3 tools/export_loot_tables.py              # writes docs/loot-tables.md
  python3 tools/export_loot_tables.py --strict     # also fails on spec violations
  python3 tools/export_loot_tables.py --check      # print the verdict only, write nothing
"""
import argparse
import datetime as dt
import json
import os
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
LOOT_ROOT = os.path.join(REPO, "src", "main", "resources", "assets", "hbm", "loot_tables")
OUT_MD = os.path.join(REPO, "docs", "loot-tables.md")

# directory -> purpose (the naming convention from section 15)
USAGE = OrderedDict([
    ("blocks", "Block drops (`Block#getLootTable()` defaults to `hbm:blocks/<registry name>`)"),
    ("entities", "Entity drops (`Entity#getLootTable()` overridden to return `hbm:entities/<registry name>`)"),
    ("machines", "Machine/container contents (generated with `LootTable#fillInventory`)"),
    ("chests", "structure chests"),
    ("misc", "other"),
])


def table_name(rel_path):
    """Relative path → table name: everything under assets/hbm/loot_tables, minus .json — i.e. the ResourceLocation's path."""
    path = rel_path.replace(os.sep, "/")
    if path.endswith(".json"):
        path = path[:-5]
    return "hbm:" + path


def usage_of(rel_path):
    head = rel_path.replace(os.sep, "/").split("/", 1)[0]
    return USAGE.get(head, "Unclassified (outside §15's blocks/entities/machines/chests/misc)")


def read_pools(path):
    """Reads one table, returns (pools, problems). Each pools entry: {name, entries}."""
    pools = []
    problems = []
    with open(path, "r", encoding="utf-8") as fh:
        try:
            data = json.load(fh)
        except ValueError as ex:
            return [], ["JSON parse failed: %s" % ex]

    for index, pool in enumerate(data.get("pools", [])):
        name = pool.get("name")
        if not name:
            problems.append("Pool #%d is missing `name` (§15: every pool of a non-minecraft table must have a unique name)" % (index + 1))
        entries = []
        for entry in pool.get("entries", []):
            entries.append(describe_entry(entry))
        pools.append({"name": name, "entries": entries, "rolls": pool.get("rolls")})

    names = [p["name"] for p in pools if p["name"]]
    for dup in sorted(set(n for n in names if names.count(n) > 1)):
        problems.append("duplicate pool name: %s (pool names are a public API and must be unique and stable long-term)" % dup)

    return pools, problems


def describe_entry(entry):
    """Each entry records only the two things a script author actually cares about: type + name/item id, plus weight."""
    etype = entry.get("type", "?")
    label = entry.get("name") or entry.get("entryName") or entry.get("item") or "-"
    if "item" in entry:
        label = str(entry["item"])
    weight = entry.get("weight")
    return "%s / %s%s" % (etype, label, "" if weight is None else " (weight %s)" % weight)


def collect():
    """Returns (tables, problems); each tables entry: {name, rel, usage, pools}."""
    tables = []
    problems = []

    if not os.path.isdir(LOOT_ROOT):
        return tables, problems

    for root, _dirs, files in os.walk(LOOT_ROOT):
        for fname in sorted(files):
            if not fname.endswith(".json"):
                continue
            full = os.path.join(root, fname)
            rel = os.path.relpath(full, LOOT_ROOT)
            pools, probs = read_pools(full)
            tables.append({
                "name": table_name(rel),
                "rel": rel.replace(os.sep, "/"),
                "usage": usage_of(rel),
                "pools": pools,
            })
            for prob in probs:
                problems.append("%s: %s" % (rel.replace(os.sep, "/"), prob))

    tables.sort(key=lambda t: t["name"])
    return tables, problems


def render(tables, problems):
    lines = []
    lines.append("# Loot Table Listing")
    lines.append("")
    lines.append("> This file is generated by `tools/export_loot_tables.py`, **do not hand-edit**; rerun once the content layer lays down tables.")
    lines.append("> Generated at: %s" % dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    lines.append("")
    lines.append("## Naming conventions (contract §15)")
    lines.append("")
    lines.append("| Purpose | Path |")
    lines.append("|---|---|")
    for key, desc in USAGE.items():
        lines.append("| %s | `assets/hbm/loot_tables/%s/<registry name>.json` |" % (desc, key))
    lines.append("")
    lines.append("Hard requirements:")
    lines.append("")
    lines.append("1. **For tables outside the `minecraft` namespace, every pool must have a unique `name`**; otherwise Forge fails to load outright with `JsonParseException`.")
    lines.append("2. Entries that pack authors need to **remove individually** should be given an `entryName`.")
    lines.append("3. **Pool names / entry names are a public API** — they're the scripts' anchors; renaming one breaks someone else's scripts, so they must stay stable long-term.")
    lines.append("4. The table name is `hbm:<relative path>` (e.g. `assets/hbm/loot_tables/blocks/ore_uranium.json` → `hbm:blocks/ore_uranium`).")
    lines.append("5. The mod itself must **not** `setTable()` a whole table in `LootTableLoadEvent` (it would wash out the tweaker's changes).")
    lines.append("")
    lines.append("## Overview")
    lines.append("")
    lines.append("- Table count: **%d**" % len(tables))

    by_dir = OrderedDict()
    for table in tables:
        head = table["rel"].split("/", 1)[0] if "/" in table["rel"] else "(root)"
        by_dir[head] = by_dir.get(head, 0) + 1
    if by_dir:
        lines.append("- Distribution:" + "、".join("%s %d" % (k, v) for k, v in sorted(by_dir.items())))
    lines.append("")

    if not tables:
        lines.append("## Status: generated as the content layer lands")
        lines.append("")
        lines.append("There are **no tables under `assets/hbm/loot_tables/` yet** (the directory skeleton is in place).")
        lines.append("§15 rules that all drops go through standard JSON tables and forbids Java hardcoding, so these tables are produced by the content layer (A3 blocks /")
        lines.append("A5 items / A4 entities) as their domains land, and this listing fills in automatically.")
        lines.append("")
        lines.append("Until then, spot-check hardcoded drops with `tools/verify/check_loot_hardcode.py` (the hit count should be 0).")
        return "\n".join(lines) + "\n"

    lines.append("## Per-table details")
    lines.append("")
    for table in tables:
        lines.append("### `%s`" % table["name"])
        lines.append("")
        lines.append("- File: `assets/hbm/loot_tables/%s`" % table["rel"])
        lines.append("- Purpose: %s" % table["usage"])
        if not table["pools"]:
            lines.append("- Pools: **(no pool)** — an empty table is still visible to the tweaker, but that's usually not intended; please confirm.")
            lines.append("")
            continue
        lines.append("- %d pools:" % len(table["pools"]))
        for pool in table["pools"]:
            rolls = "" if pool["rolls"] is None else "，rolls %s" % pool["rolls"]
            lines.append("  - `%s`%s" % (pool["name"] or "(missing name!)", rolls))
            if not pool["entries"]:
                lines.append("    - (no entries)")
            for entry in pool["entries"]:
                lines.append("    - %s" % entry)
        lines.append("")

    lines.append("## Convention checks")
    lines.append("")
    if problems:
        lines.append("Found **%d** problems:" % len(problems))
        lines.append("")
        for prob in problems:
            lines.append("- %s" % prob)
    else:
        lines.append("All tables pass: every pool has a unique `name`.")
    lines.append("")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Exports the HBM loot table listing")
    parser.add_argument("--strict", action="store_true", help="Returns nonzero on convention violations (can be hung into acceptance)")
    parser.add_argument("--check", action="store_true", help="Prints only the verdict, doesn't write docs/loot-tables.md")
    args = parser.parse_args()

    tables, problems = collect()

    if args.check:
        print("tables: %d, convention problems: %d" % (len(tables), len(problems)))
        for prob in problems:
            print("  - %s" % prob)
    else:
        text = render(tables, problems)
        os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
        with open(OUT_MD, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("Wrote %s (%d tables, %d convention problems)" % (os.path.relpath(OUT_MD, REPO), len(tables), len(problems)))

    if args.strict and problems:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
