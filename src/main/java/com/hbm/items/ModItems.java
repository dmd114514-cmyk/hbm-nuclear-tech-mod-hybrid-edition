/**
 * The item registration holder class.
 *
 * The original was a 587KB, 7,192-line monster — declarations, instantiation, ore dict and registration all jammed together. Now it does two things:
 * **① declare every item field; ② hand instantiation to registrars per subdomain**. The fields stay here because
 * the whole project (ore dict, recipes, machines, manual) references `ModItems.<name>` directly — scattering them means touching a thousand call sites,
 * not worth it. The real construction logic lives in the registrars under the `registry` package; none of them gets to grow into a beast again.
 *
 * Creative tabs used to be MainRegistry's job; they now belong to the content layer's tab subdomain. Only an injectable reference stays here,
 * **defaulting to MISC rather than null**: items idling in the misc tab beat items vanishing outright, or
 * `getSubItems(SEARCH)` silently skipping entries over null tabs. Inject by name once the tab subdomain lands.
 */
