	@Override
	public void preInit() {
		for(IRegistrar r : SUB) r.preInit();
	}

	@Override
	public void init() {
		for(IRegistrar r : SUB) r.init();
	}

	@Override
	public void postInit() {
		for(IRegistrar r : SUB) r.postInit();

		// The infinite bucket item lives on the item side while the check lives on the inventory side, so "which item counts as infinite" is handed over here.
		// If the item itself hasn't migrated, what's assigned is null and the inventory side treats it as "no infinite bucket" — no errors.
		com.hbm.inventory.fluid.tank.FluidTank.infiniteBarrel = fluid_barrel_infinite;

		// Which material a scrap carries only the item side can compute; the material layer left an injection point waiting
		com.hbm.inventory.material.Mats.scrapMats = com.hbm.items.machine.ItemScraps::getMats;
	}

	@Override
	public void registerModels() {
		for(IRegistrar r : SUB) r.registerModels();
	}

